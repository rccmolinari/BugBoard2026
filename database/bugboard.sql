CREATE TYPE public.issuestato AS ENUM (
    'TODO',
    'IN_PROGRESS',
    'DONE',
    'EXPIRED',
    'CLOSED'
);

CREATE TYPE public.issuetipo AS ENUM (
    'QUESTION',
    'BUG',
    'DOCUMENTATION',
    'FEATURE'
);

CREATE TYPE public.utenteruolo AS ENUM (
    'ADMIN',
    'USER',
    'READONLY'
);

CREATE TABLE public.utente (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email varchar(255) NOT NULL UNIQUE,
    password varchar(255) NOT NULL,
    name varchar(100) NOT NULL,
    surname varchar(100) NOT NULL,
    role public.utenteruolo NOT NULL
);

CREATE TABLE public.issue (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version bigint NOT NULL,
    titolo varchar(255) NOT NULL,
    descrizione text NOT NULL,
    priorita integer,
    immagine bytea,
    immagine_content_type varchar(50),
    tipo public.issuetipo NOT NULL,
    stato public.issuestato NOT NULL,
    datascadenza timestamp without time zone,
    datacreazione timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
    etichetta text[],
    commento jsonb,
    idcreatore integer NOT NULL REFERENCES public.utente (id),
    idassegnatario integer REFERENCES public.utente (id),
    assegnato_a integer REFERENCES public.utente (id)
);

CREATE TABLE public.notifica (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idissue integer NOT NULL REFERENCES public.issue (id),
    idassegnatario integer NOT NULL REFERENCES public.utente (id),
    idassegnato_a integer NOT NULL REFERENCES public.utente (id),
    letta boolean NOT NULL DEFAULT false,
    datacreazione timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE public.sessione (
    sid uuid PRIMARY KEY,
    userid integer NOT NULL REFERENCES public.utente (id),
    created_at timestamp without time zone DEFAULT CURRENT_TIMESTAMP
);
